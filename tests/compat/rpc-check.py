"""Check that rpc/rpcl/block.x stays wire compatible with released versions.

Every released block.x is kept in tests/compat/rpc/block-v<version>.x. The
current block.x must still offer everything a baseline offers:

- the programs and versions with the same numbers,
- every procedure with the same number, name, argument and result type,
- every type those procedures use, directly or through other types, with
  the same definition: struct fields in the same order with the same type,
  name and size, enum members with the same value (new members are
  allowed), the same typedefs and constants,
- the same XDR routines generated by rpcgen for those types (when rpcgen
  is installed), which catches what the parser could miss.

New procedures, versions, programs and types are allowed. A procedure that
needs other arguments must be a new procedure: hosts in a cluster and the
local clients (cli, gluster-block-apid) are upgraded one by one.

  rpc-check.py [--current FILE] [--baselines DIR] [--no-rpcgen]
  rpc-check.py --self-test
  rpc-check.py --snapshot VERSION     add the current block.x as baseline
  rpc-check.py --snapshot VERSION --from vVERSION
                                      add block.x of a git tag as baseline

A release adds its block.x as baseline (--snapshot) in the release commit.
"""

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile

TOP = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DEF_CURRENT = os.path.join(TOP, "rpc", "rpcl", "block.x")
DEF_BASELINES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "rpc")

# XDR base types, not defined in the .x file
BASE_TYPES = {
    "int", "unsigned", "u_int", "long", "u_long", "short", "u_short",
    "char", "u_char", "hyper", "u_hyper", "quad_t", "u_quad_t", "int64_t",
    "uint64_t", "int32_t", "uint32_t", "float", "double", "bool", "bool_t",
    "string", "opaque", "void", "enum", "struct", "union",
}


class RpcxError(Exception):
    pass


def strip(text):
    """Remove comments, rpcgen pass-through (%) and preprocessor lines."""
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", " ", text)
    lines = []
    for line in text.split("\n"):
        s = line.strip()
        if s.startswith("%") or s.startswith("#"):
            continue
        lines.append(line)
    return "\n".join(lines)


TOKEN = re.compile(r"[A-Za-z_][A-Za-z0-9_]*|0x[0-9A-Fa-f]+|-?[0-9]+|[{}()<>\[\];=,*:]")


def tokenize(text):
    text = strip(text)
    pos = 0
    toks = []
    for m in TOKEN.finditer(text):
        gap = text[pos:m.start()]
        if gap.strip():
            raise RpcxError("unexpected text %r" % gap.strip()[:40])
        toks.append(m.group(0))
        pos = m.end()
    if text[pos:].strip():
        raise RpcxError("unexpected text %r" % text[pos:].strip()[:40])
    return toks


class Parser(object):
    def __init__(self, toks):
        self.t = toks
        self.i = 0

    def peek(self):
        return self.t[self.i] if self.i < len(self.t) else None

    def next(self):
        if self.i >= len(self.t):
            raise RpcxError("unexpected end of file")
        tok = self.t[self.i]
        self.i += 1
        return tok

    def expect(self, tok):
        got = self.next()
        if got != tok:
            raise RpcxError("expected %r, got %r near token %d" % (tok, got, self.i))
        return got

    def until(self, stop):
        """Tokens up to (not including) the first token in stop."""
        out = []
        while self.peek() not in stop:
            out.append(self.next())
        return out


def num(tok, consts):
    if tok in consts:
        return num(consts[tok], consts)
    try:
        return int(tok, 0)
    except ValueError:
        raise RpcxError("not a number: %r" % tok)


def parse(text):
    """Parse a .x file into a dict of definitions."""
    p = Parser(tokenize(text))
    d = {"struct": {}, "enum": {}, "typedef": {}, "const": {}, "union": {},
         "program": {}}

    while p.peek() is not None:
        kw = p.next()
        if kw == "const":
            name = p.next()
            p.expect("=")
            d["const"][name] = p.next()
            p.expect(";")
        elif kw == "typedef":
            decl = p.until({";"})
            p.expect(";")
            d["typedef"][decl[-1] if decl[-1] not in "]>" else decl_name(decl)] = decl
        elif kw == "enum":
            name = p.next()
            p.expect("{")
            members = []
            while p.peek() != "}":
                mname = p.next()
                val = None
                if p.peek() == "=":
                    p.next()
                    val = p.next()
                members.append((mname, val))
                if p.peek() == ",":
                    p.next()
            p.expect("}")
            p.expect(";")
            vals = {}
            last = -1
            for idx, (mname, val) in enumerate(members):
                last = num(val, d["const"]) if val is not None else last + 1
                # a trailing FOO_MAX without value only counts the members, it
                # is never sent and moves when members are added before it
                if (idx == len(members) - 1 and val is None
                        and mname.endswith("_MAX")):
                    continue
                vals[mname] = last
            d["enum"][name] = vals
        elif kw in ("struct", "union"):
            name = p.next()
            depth = 0
            body = []
            p.expect("{") if kw == "struct" else None
            if kw == "union":
                # keep unions as raw tokens, they are compared as a whole
                while True:
                    tok = p.next()
                    if tok == "{":
                        depth += 1
                    elif tok == "}":
                        depth -= 1
                        if depth == 0:
                            break
                    body.append(tok)
                p.expect(";")
                d["union"][name] = body
                continue
            fields = []
            while p.peek() != "}":
                decl = p.until({";"})
                p.expect(";")
                fields.append(decl)
            p.expect("}")
            p.expect(";")
            d["struct"][name] = fields
        elif kw == "program":
            pname = p.next()
            p.expect("{")
            versions = {}
            while p.peek() == "version":
                p.next()
                vname = p.next()
                p.expect("{")
                procs = {}
                while p.peek() != "}":
                    res = p.until({"("})[:]
                    pr = res.pop()
                    p.expect("(")
                    args = p.until({")"})
                    p.expect(")")
                    p.expect("=")
                    pnum = num(p.next(), d["const"])
                    p.expect(";")
                    args = [a for a in args if a != ","]
                    if pnum in procs:
                        raise RpcxError("%s: procedure number %d used twice" % (vname, pnum))
                    procs[pnum] = {"name": pr, "result": res, "args": args}
                p.expect("}")
                p.expect("=")
                vnum = num(p.next(), d["const"])
                p.expect(";")
                versions[vnum] = {"name": vname, "procs": procs}
            p.expect("}")
            p.expect("=")
            prnum = num(p.next(), d["const"])
            p.expect(";")
            d["program"][prnum] = {"name": pname, "versions": versions}
        else:
            raise RpcxError("unexpected %r at top level" % kw)
    return d


def decl_name(decl):
    for i, tok in enumerate(decl):
        if tok in ("[", "<"):
            return decl[i - 1]
    return decl[-1]


def type_refs(tokens, d):
    """Names of types defined in the file that tokens refer to."""
    refs = set()
    for tok in tokens:
        if tok in BASE_TYPES:
            continue
        for kind in ("struct", "enum", "typedef", "union", "const"):
            if tok in d[kind]:
                refs.add((kind, tok))
    return refs


def closure(d):
    """All (kind, name) the procedures of d use."""
    todo = set()
    for prog in d["program"].values():
        for ver in prog["versions"].values():
            for proc in ver["procs"].values():
                todo |= type_refs(proc["result"] + proc["args"], d)
    seen = set()
    while todo:
        item = todo.pop()
        if item in seen:
            continue
        seen.add(item)
        kind, name = item
        if kind == "struct":
            for decl in d["struct"][name]:
                todo |= type_refs(decl, d)
        elif kind in ("typedef", "union"):
            todo |= type_refs(d[kind][name], d)
        elif kind == "const":
            todo |= type_refs([d["const"][name]], d)
    return seen


def show(decl):
    return " ".join(decl)


def compare(base, cur, label):
    errs = []

    for prnum, bprog in sorted(base["program"].items()):
        cprog = cur["program"].get(prnum)
        if not cprog:
            errs.append("%s: program %s (%d) is gone" % (label, bprog["name"], prnum))
            continue
        if cprog["name"] != bprog["name"]:
            errs.append("%s: program %d renamed %s -> %s"
                        % (label, prnum, bprog["name"], cprog["name"]))
        for vnum, bver in sorted(bprog["versions"].items()):
            cver = cprog["versions"].get(vnum)
            if not cver:
                errs.append("%s: %s version %s (%d) is gone"
                            % (label, bprog["name"], bver["name"], vnum))
                continue
            for pnum, bproc in sorted(bver["procs"].items()):
                cproc = cver["procs"].get(pnum)
                where = "%s: %s procedure %d (%s)" % (label, bprog["name"], pnum, bproc["name"])
                if not cproc:
                    errs.append("%s is gone" % where)
                    continue
                if cproc["name"] != bproc["name"]:
                    errs.append("%s renamed to %s" % (where, cproc["name"]))
                if cproc["args"] != bproc["args"]:
                    errs.append("%s argument changed: %s -> %s"
                                % (where, show(bproc["args"]), show(cproc["args"])))
                if cproc["result"] != bproc["result"]:
                    errs.append("%s result changed: %s -> %s"
                                % (where, show(bproc["result"]), show(cproc["result"])))

    for kind, name in sorted(closure(base)):
        b = base[kind][name]
        c = cur[kind].get(name)
        where = "%s: %s %s" % (label, kind, name)
        if c is None:
            errs.append("%s is gone" % where)
            continue
        if kind == "struct":
            if len(c) != len(b):
                errs.append("%s has %d fields, was %d: change a struct by adding a "
                            "new one and a new procedure" % (where, len(c), len(b)))
            for i, (bf, cf) in enumerate(zip(b, c)):
                if bf != cf:
                    errs.append("%s field %d changed: '%s' -> '%s'"
                                % (where, i + 1, show(bf), show(cf)))
        elif kind == "enum":
            for mname, val in sorted(b.items(), key=lambda kv: kv[1]):
                if mname not in c:
                    errs.append("%s member %s is gone" % (where, mname))
                elif c[mname] != val:
                    errs.append("%s member %s changed value %d -> %d"
                                % (where, mname, val, c[mname]))
        elif kind == "const":
            if num(b, base["const"]) != num(c, cur["const"]):
                errs.append("%s changed %s -> %s" % (where, b, c))
        elif b != c:
            errs.append("%s changed: '%s' -> '%s'" % (where, show(b), show(c)))
    return errs


XDR_FUNC = re.compile(r"^bool_t\s*\nxdr_(\w+)\s*\(.*?\n\}\n", re.S | re.M)


def rpcgen_xdr(path, workdir):
    out = os.path.join(workdir, os.path.basename(path) + ".xdr.c")
    # rpcgen writes #include "<name>.h" lines, we only look at the routines
    subprocess.check_call(["rpcgen", "-c", "-o", out, path],
                          cwd=workdir, stdout=subprocess.DEVNULL)
    with open(out) as f:
        text = f.read()
    funcs = {}
    for m in XDR_FUNC.finditer(text):
        funcs[m.group(1)] = re.sub(r"\s+", " ", m.group(0)).strip()
    return funcs


def compare_xdr(bpath, cpath, base, label):
    errs = []
    work = tempfile.mkdtemp(prefix="rpc-check-")
    try:
        # rpcgen names its output after the input, copy both under one name
        bdir = os.path.join(work, "base")
        cdir = os.path.join(work, "cur")
        os.mkdir(bdir)
        os.mkdir(cdir)
        shutil.copy(bpath, os.path.join(bdir, "block.x"))
        shutil.copy(cpath, os.path.join(cdir, "block.x"))
        bx = rpcgen_xdr(os.path.join(bdir, "block.x"), bdir)
        cx = rpcgen_xdr(os.path.join(cdir, "block.x"), cdir)
    finally:
        shutil.rmtree(work, ignore_errors=True)
    if not bx:
        raise RpcxError("no XDR routines found in the rpcgen output of %s" % bpath)

    for kind, name in sorted(closure(base)):
        if kind in ("const", "enum"):
            # xdr_enum() does not depend on the members
            continue
        if name not in bx:
            errs.append("%s: no rpcgen XDR routine for %s %s" % (label, kind, name))
            continue
        if cx.get(name) != bx[name]:
            errs.append("%s: rpcgen XDR routine of %s %s changed" % (label, kind, name))
    return errs


def baselines(bdir):
    out = []
    for fname in sorted(os.listdir(bdir)):
        m = re.match(r"block-v([0-9.]+)\.x$", fname)
        if m:
            out.append((m.group(1), os.path.join(bdir, fname)))
    return out


def check(current, bdir, use_rpcgen):
    with open(current) as f:
        cur = parse(f.read())
    files = baselines(bdir)
    if not files:
        raise RpcxError("no baselines in %s" % bdir)
    errs = []
    for version, path in files:
        label = "v" + version
        with open(path) as f:
            base = parse(f.read())
        errs += compare(base, cur, label)
        if use_rpcgen:
            errs += compare_xdr(path, current, base, label)
    return [v for v, _ in files], errs


def self_test(current, use_rpcgen):
    """Break the current block.x in typical ways, each must be reported."""
    with open(current) as f:
        text = f.read()
    cases = [
        ("change a field type",
         r"(struct blockDelete \{\s*char\s+block_name)\[255\]", r"\1[256]"),
        ("rename a field",
         r"(struct blockHostsCli \{\s*char\s+)volume", r"\1volname"),
        ("insert a field",
         r"(struct blockModifyPrio \{)", r"\1\n  bool new_flag;"),
        ("drop the last field",
         r"(struct blockReload \{\s*char\s+block_name\[255\];)\s*char\s+gbid\[127\];", r"\1"),
        ("renumber a procedure",
         r"BLOCK_HOST_TPG\(blockHostTpg\) = 11;", "BLOCK_HOST_TPG(blockHostTpg) = 12;"),
        ("remove a procedure",
         r"\s*blockResponse BLOCK_RELOAD_CLI\(blockReloadCli\) = 9;", ""),
        ("change an argument",
         r"BLOCK_DELETE\(blockDelete\)", "BLOCK_DELETE(blockReload)"),
        ("change an enum value",
         r"GB_JSON_PRETTY\s*= 3", "GB_JSON_PRETTY = 7"),
        ("change a program number",
         r"\} = 212153113;", "} = 212153114;"),
        ("change a version number",
         r"(GLUSTER_BLOCK_VERS \{.*?\}) = 1;", r"\1 = 2;"),
    ]
    ok_cases = [
        ("add a procedure",
         r"(BLOCK_HOST_MAINT_CLI\(blockHostMaintCli\) = 14;)",
         r"\1\n    blockResponse BLOCK_NEW_CLI(blockNewCli) = 999;"),
        ("add a struct",
         r"(struct blockResponse \{)", r"struct blockNewCli {\n  char volume[255];\n};\n\n\1"),
        ("add an enum member",
         r"(GB_JSON_DEFAULT\s*= 4,)", r"\1\n  GB_JSON_EXTRA = 5,"),
    ]
    failed = 0
    tmp = tempfile.mkdtemp(prefix="rpc-selftest-")
    try:
        bdir = os.path.join(tmp, "rpc")
        os.mkdir(bdir)
        shutil.copy(current, os.path.join(bdir, "block-v0.0.0.x"))
        for expect_fail, items in ((True, cases), (False, ok_cases)):
            for what, pat, repl in items:
                broken, n = re.subn(pat, repl, text, count=1, flags=re.S)
                if n != 1:
                    print("self-test: pattern of '%s' does not match block.x" % what)
                    failed += 1
                    continue
                path = os.path.join(tmp, "block.x")
                with open(path, "w") as f:
                    f.write(broken)
                _, errs = check(path, bdir, use_rpcgen)
                if bool(errs) != expect_fail:
                    failed += 1
                    print("self-test FAIL: %s: %s" % (what, errs or "not reported"))
                else:
                    print("self-test ok: %s%s" % (what, (" -> " + errs[0]) if errs else ""))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    return failed


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--current", default=DEF_CURRENT)
    ap.add_argument("--baselines", default=DEF_BASELINES)
    ap.add_argument("--no-rpcgen", action="store_true",
                    help="skip the comparison of the generated XDR routines")
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--snapshot", metavar="VERSION")
    ap.add_argument("--from", dest="ref", metavar="GITREF",
                    help="with --snapshot: take block.x of this git tag or commit")
    a = ap.parse_args()

    use_rpcgen = not a.no_rpcgen
    if use_rpcgen and not shutil.which("rpcgen"):
        print("rpc-check: rpcgen not found, XDR routines not compared")
        use_rpcgen = False

    try:
        if a.snapshot:
            if not re.match(r"^[0-9]+\.[0-9]+\.[0-9]+$", a.snapshot):
                raise RpcxError("version must be X.Y.Z")
            dest = os.path.join(a.baselines, "block-v%s.x" % a.snapshot)
            if os.path.exists(dest):
                raise RpcxError("%s exists" % dest)
            if a.ref:
                text = subprocess.check_output(
                    ["git", "-C", TOP, "show", "%s:rpc/rpcl/block.x" % a.ref])
                parse(text.decode())
                with open(dest, "wb") as f:
                    f.write(text)
            else:
                if baselines(a.baselines):
                    _, errs = check(a.current, a.baselines, use_rpcgen)
                    if errs:
                        raise RpcxError("current block.x is not compatible, no snapshot")
                shutil.copy(a.current, dest)
            print("rpc-check: added %s" % dest)
            return 0

        if a.self_test:
            failed = self_test(a.current, use_rpcgen)
            print("rpc-check self-test: %s" % ("FAILED" if failed else "passed"))
            return 1 if failed else 0

        versions, errs = check(a.current, a.baselines, use_rpcgen)
    except (RpcxError, subprocess.CalledProcessError, OSError) as e:
        print("rpc-check: %s" % e)
        return 2

    for e in errs:
        print("rpc-check: %s" % e)
    if errs:
        print("rpc-check: block.x breaks the RPC of released versions.\n"
              "Never change what a released version sends: add a new struct and a\n"
              "new procedure (and a capability if other hosts must support it).")
        return 1
    print("rpc-check: block.x is compatible with %s%s"
          % (", ".join("v" + v for v in versions),
             "" if use_rpcgen else " (XDR routines not compared)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
